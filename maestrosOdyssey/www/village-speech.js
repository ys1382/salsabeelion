  function foldWord(lang, word) {
    var s = String(word || "");
    if (lang === "tr") s = s.replace(/\u0130/g, "i").replace(/\u0049/g, "\u0131");
    s = s.toLowerCase();
    if (lang === "ar") {
      s = s.replace(/[\u064B-\u0652\u0670\u0640]/g, "");
      s = s.replace(/[أإآ]/g, "ا");
      s = s.replace(/ة/g, "ه");
      s = s.replace(/^ال/, "");
    } else if (lang !== "ja") {
      s = s.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    }
    s = s.replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, "");
    return s;
  }

  function heardTokens(lang, transcript) {
    return String(transcript || "").split(/[^\p{L}\p{M}\p{N}]+/u).map(function (word) {
      return foldWord(lang, word);
    }).filter(Boolean);
  }

  function wordHit(lang, target, heardList, heardFlat) {
    var folded = foldWord(lang, target);
    if (!folded) return true;
    var alias = (window.VILLAGE_ALIAS[lang] && window.VILLAGE_ALIAS[lang][target]) || [];
    var forms = [folded];
    alias.forEach(function (item) {
      forms.push(foldWord(lang, item));
    });
    if (lang === "ja") {
      var i;
      for (i = 0; i < forms.length; i++) {
        if (forms[i] && heardFlat.indexOf(forms[i]) !== -1) return true;
      }
      return false;
    }
    var h;
    for (h = 0; h < heardList.length; h++) {
      var heard = heardList[h];
      var f;
      for (f = 0; f < forms.length; f++) {
        if (!forms[f]) continue;
        if (heard === forms[f]) return true;
        if (forms[f].length > 3 && (heard.indexOf(forms[f]) !== -1 || forms[f].indexOf(heard) !== -1)) return true;
      }
    }
    return false;
  }

  window.villageGrade = function (lang, targetWords, transcripts, ratio) {
    var heardList = [];
    var flat = "";
    (transcripts || []).forEach(function (text) {
      if (lang === "ja") flat += String(text || "").replace(/[^\p{L}\p{N}]/gu, "");
      else heardList = heardList.concat(heardTokens(lang, text));
    });
    var skip = SKIP[lang] || {};
    var hits = [];
    var need = 0;
    var got = 0;
    targetWords.forEach(function (word) {
      var folded = foldWord(lang, word);
      var ok = wordHit(lang, word, heardList, flat);
      hits.push(ok);
      if (!folded || skip[folded]) return;
      need += 1;
      if (ok) got += 1;
    });
    if (!need) {
      need = hits.length;
      got = hits.filter(Boolean).length;
    }
    var passed = need ? (got / need) >= ratio : false;
    if (passed) {
      hits = hits.map(function (ok, index) {
        if (ok) return true;
        var folded = foldWord(lang, targetWords[index]);
        return !!skip[folded];
      });
    }
    return { passed: passed, hits: hits, got: got, need: need };
  };
